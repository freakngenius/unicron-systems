#!/usr/bin/env node
// scripts/generate-agent-cron.mjs — Sprint 7.5 H1
//
// Reads schedule_cron from nervous_system.agents and writes a TS module that
// inngest-fns.ts imports at registration time. Run as a prebuild step so the
// deployed Inngest function definitions honor the latest DB values.
//
// Fallback shape: if Supabase is unreachable or returns no schedule_cron for an
// agent, the consumer is expected to fall back to a hardcoded literal. This
// keeps build green when the DB is briefly unavailable.

import { createClient } from '@supabase/supabase-js';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, '../lib/agents/generated-agent-cron.ts');

const url = process.env.SUPABASE_URL ?? process.env.VITE_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;

async function fetchAgentCronMap() {
  if (!url || !key) {
    console.warn('[generate-agent-cron] SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY missing — emitting empty map. Cron values fall back to literals.');
    return {};
  }
  const sb = createClient(url, key);
  const { data, error } = await sb.rpc('ns_list_agents');
  if (error) {
    console.warn(`[generate-agent-cron] ns_list_agents error: ${error.message} — emitting empty map.`);
    return {};
  }
  const map = {};
  for (const row of data ?? []) {
    if (row?.name && typeof row.schedule_cron === 'string' && row.schedule_cron.length > 0) {
      map[row.name] = row.schedule_cron;
    }
  }
  return map;
}

const map = await fetchAgentCronMap();

const ts = `// AUTO-GENERATED by scripts/generate-agent-cron.mjs — DO NOT EDIT BY HAND.
// Source: nervous_system.agents.schedule_cron via public.ns_list_agents().
// Regenerated on each build (\`npm run prebuild\`). Honored at Inngest
// function registration in lib/agents/inngest-fns.ts.

export const GENERATED_AGENT_CRON: Record<string, string> = ${JSON.stringify(map, null, 2)} as const;

export const GENERATED_AT = ${JSON.stringify(new Date().toISOString())};

export function agentCron(agentName: string, fallback: string): string {
  return GENERATED_AGENT_CRON[agentName] ?? fallback;
}
`;

mkdirSync(dirname(OUT_PATH), { recursive: true });
writeFileSync(OUT_PATH, ts, 'utf-8');
console.log(`[generate-agent-cron] wrote ${OUT_PATH} with ${Object.keys(map).length} agent cron entries`);
